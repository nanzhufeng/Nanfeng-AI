import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
import { icon, icons } from '../src/icon-source.mjs';
import { renderSafeMarkdown } from '../src/safe-markdown.mjs';
const source = readFileSync(new URL('../src/app.mjs', import.meta.url), 'utf8');
const extract = (start, end) => source.slice(source.indexOf(start), source.indexOf(end, source.indexOf(start)));
const escape = value => String(value ?? '').replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
test('production reader centers filename, presents labelled icon menu and renders inert body title', () => {
  const state = { textPreview: { displayName: '说明.md', attachmentId: 'a', workspaceId: 'w', mimeType: 'text/markdown', byteCount: 1, text: '正文' } };
  const ctx = vm.createContext({ state, escape, icon, icons, bytes: n => String(n), renderSafeMarkdown });
  vm.runInContext(extract('function textPreviewDialog()', '\nfunction archiveDirectoryRows'), ctx);
  let html = ctx.textPreviewDialog();
  assert.match(html, /text-preview-title">说明.md/);
  assert.match(html, /<h1>说明<\/h1>/);
  for (const label of ['下载文件', '分享文件', '复制文本']) assert.ok(html.includes(`<span>${label}</span>`));
  assert.match(html, /close-text-preview" aria-label="返回/);
  state.textPreview.text = '# 已有标题\n正文';
  html = ctx.textPreviewDialog();
  assert.equal((html.match(/<h[1-6]>/g) || []).length, 1);
  assert.ok(!html.includes('<h1>说明</h1>'));
  state.textPreview.text = '<script>alert(1)</script>';
  assert.ok(!ctx.textPreviewDialog().includes('<script>'));
});
test('production cloud batch cancellation never recycles local data and removes only acknowledged rows', async () => {
  const rows = [{ id: 'c1', workspaceId: 'w', revision: 1 }, { id: 'c2', workspaceId: 'w', revision: 1 }];
  const calls = [];
  const state = { dialog: { kind: 'conversation-batch-delete', items: rows }, current: { summary: { id: 'w' } }, cloudConversations: [...rows], selectedConversationId: 'c1' };
  const ctx = vm.createContext({ state, native: true, cloudListReadGeneration: 0, batchConversationKey: row => `${row.workspaceId}:${row.id}`, captureCloudSidebarWorkspace: () => null, ensureConversationActionWorkspace: async () => {}, restoreCloudSidebarWorkspace: async () => {}, loadDesktopAccountSync: async () => {}, refresh: async () => {}, render: () => {}, persistCloudConversationCache: () => {}, finishConversationBatchEditing: () => {}, invoke: async (command, args) => { calls.push({ command, args }); if (command !== 'cancel_desktop_conversation_sync') throw Error('local mutation forbidden'); } });
  vm.runInContext(extract('async function confirmConversationBatchDelete()', '\n// A cloud row'), ctx);
  await ctx.confirmConversationBatchDelete();
  assert.equal(calls.length, 2);
  assert.equal(state.cloudConversations.length, 0);
  assert.equal(state.selectedConversationId, 'c1');
  assert.match(state.status, /本地对话保留/);
});
test('production video checkpoints exact zero, ignores unrestored metadata and serializes writes', async () => {
  const video = { isConnected: true, readyState: 1, currentTime: 9 };
  const state = { videoPreview: { attachmentId: 'a', workspaceId: 'w' } };
  const calls = [];
  const ctx = vm.createContext({ state, native: true, document: { querySelector: () => video }, Date, Promise, invoke: async (_, { args }) => calls.push(args) });
  vm.runInContext(extract('function persistVideoPreviewPosition(', '\nasync function openVideoPreview'), ctx);
  ctx.persistVideoPreviewPosition(true);
  state.videoPreview.resumeReady = true;
  ctx.persistVideoPreviewPosition(true);
  video.currentTime = 0;
  ctx.persistVideoPreviewPosition(true);
  await vm.runInContext('videoResumeWrite', ctx);
  assert.deepEqual(calls.map(row => row.positionMillis), [9000, 0]);
  assert.ok(calls.every(row => row.attachmentId === 'a' && row.workspaceId === 'w'));
});
